def _currency(currency: str) -> str:
    code = str(currency).strip().upper()
    if code not in ILLUSTRATIVE_SWAPTION_NORMAL_BP:
        raise ValueError(f"no illustrative vols for {currency!r}; have {sorted(ILLUSTRATIVE_SWAPTION_NORMAL_BP)}")
    return code


def illustrative_swaption_grid(currency: str = "USD") -> VolGrid:
    """The ILLUSTRATIVE normal-vol swaption grid of a currency."""

    code = _currency(currency)
    rows = tuple(
        (e, t, float(o), v * 1e-4)
        for e, t, vols in ILLUSTRATIVE_SWAPTION_NORMAL_BP[code]
        for o, v in zip(GRID_OFFSETS_BP, vols)
    )
    return VolGrid(rows, "normal", 0.0, f"{ILLUSTRATIVE}: {code} swaption normal vols")


def illustrative_swaption_table(currency: str = "USD") -> pd.DataFrame:
    """The grid as an editable wide table: expiry, tenor, then one column
    per offset (bp of normal vol)."""

    return illustrative_swaption_grid(currency).wide()


def illustrative_cap_atm(currency: str = "USD") -> pd.DataFrame:
    """ILLUSTRATIVE flat ATM normal cap vols: columns ``maturity``, ``vol_bp``."""

    code = _currency(currency)
    return pd.DataFrame({"maturity": CAP_MATURITIES, "vol_bp": ILLUSTRATIVE_CAP_ATM_NORMAL_BP[code]})


def illustrative_cap_strikes(currency: str = "USD") -> pd.DataFrame:
    """ILLUSTRATIVE flat normal cap vols by maturity (rows) and fixed strike
    in percent (columns), bp."""

    code = _currency(currency)
    strikes = CAP_STRIKES_PCT[code]
    rows = [{"maturity": m, **{f"{k:.2f}%": v for k, v in zip(strikes, vols)}}
            for m, vols in ILLUSTRATIVE_CAP_STRIKE_NORMAL_BP[code]]  # fmt: skip
    return pd.DataFrame(rows)
